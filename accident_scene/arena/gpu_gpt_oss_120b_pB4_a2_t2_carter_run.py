def _wrap_angle(a: float) -> float:
    """Wrap angle to [-π, π]."""
    return math.atan2(math.sin(a), math.cos(a))


def _clamp(v: float, lo: float, hi: float) -> float:
    """Clamp *v* between *lo* and *hi*."""
    return max(lo, min(hi, v))


# ----------------------------------------------------------------------
#  Way‑point list (static – chosen to stay clear of all known static obstacles
#  and the moving arena_mover_04 which travels near x≈8).  The last point is the GOAL.
# ----------------------------------------------------------------------
#   (x, y) coordinates are in world frame.
# ----------------------------------------------------------------------
_WAYPOINTS = [
    (-5.0, -10.8),   # move east along the start row, staying south of everything
    (-5.0, -2.0),    # go north, now past Forklift_01 (which is at y≈-3)
    (-6.5, -2.0),    # shift west to stay clear of box 09 later on
    (-6.5, 16.5),    # go straight north all the way to the goal row (well west of moving obstacle)
    (8.0, 16.5),     # final east leg into the goal column
]

_current_wp = 0          # index of the waypoint we are currently heading for


def controller(t, pose, env):
    """Follow the static way‑points while using the front 2‑D lidar to avoid any
    dynamic obstacle that appears directly ahead *while the robot is trying to move
    forward*.  Obstacles detected during in‑place rotation are ignored.
    """
    global _current_wp
    # --------------------------------------------------------------
    #  Sensor check – front 2‑D lidar (narrow‑front filter)
    # --------------------------------------------------------------
    SAFETY_DIST = 1.0   # metres – react a bit earlier
    front_pts = lidar2d_points("front")
    obstacle_close = False
    if front_pts.size > 0:
        # keep points that are roughly in front of the robot (|y| < 0.3 m)
        forward_mask = np.abs(front_pts[:, 1]) < 0.3
        if np.any(forward_mask):
            dists = np.linalg.norm(front_pts[forward_mask], axis=1)
            if np.any(dists < SAFETY_DIST):
                obstacle_close = True

    # --------------------------------------------------------------
    #  Way‑point tracking (same logic as the reference implementation)
    # --------------------------------------------------------------
    tx, ty = _WAYPOINTS[_current_wp]
    x, y, yaw = pose
    dx = tx - x
    dy = ty - y
    dist = math.hypot(dx, dy)
    e = _wrap_angle(math.atan2(dy, dx) - yaw)

    # Advance to the next waypoint when we are close enough (except for the final goal).
    if _current_wp < len(_WAYPOINTS) - 1 and dist < 0.35:
        _current_wp += 1
        tx, ty = _WAYPOINTS[_current_wp]
        dx = tx - x
        dy = ty - y
        dist = math.hypot(dx, dy)
        e = _wrap_angle(math.atan2(dy, dx) - yaw)

    # --------------------------------------------------------------
    #  Goal alignment phase (last waypoint == GOAL)
    # --------------------------------------------------------------
    if _current_wp == len(_WAYPOINTS) - 1:
        goal_yaw_err = _wrap_angle(GOAL[2] - yaw)
        if abs(goal_yaw_err) < 0.05:
            return 0.0, 0.0, True
        w = _clamp(1.5 * goal_yaw_err, -0.6, 0.6)
        return 0.0, w, False

    # --------------------------------------------------------------
    #  Regular waypoint‑following control (identical to the proven version)
    # --------------------------------------------------------------
    if abs(e) > 0.35:
        v = 0.0
        w = _clamp(1.5 * e, -0.8, 0.8)
    else:
        v = min(0.6, 0.5 * dist + 0.1)
        w = _clamp(1.5 * e, -0.8, 0.8)

    # --------------------------------------------------------------
    #  Simple dynamic‑obstacle avoidance: if moving forward and an obstacle
    #  is directly ahead, pause (v=0, w=0) until it clears.
    # --------------------------------------------------------------
    if v > 0.0 and obstacle_close:
        v = 0.0
        w = 0.0

    return v, w, False

